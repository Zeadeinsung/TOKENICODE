/**
 * Inline SVG icons — drawn by hand, the same way the desktop app does it.
 * Everything is stroke-based on `currentColor` so icons inherit the text
 * colour of wherever they sit, and stay correct across all four accent themes.
 */

import type { CSSProperties, ReactNode } from "react";

interface IconProps {
  size?: number;
  className?: string;
  strokeWidth?: number;
  style?: CSSProperties;
}

function Icon({
  size = 16,
  className,
  strokeWidth = 1.75,
  style,
  children,
}: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={style}
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

